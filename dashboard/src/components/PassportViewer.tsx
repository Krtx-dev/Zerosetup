import { Check, Copy, Download } from 'lucide-react'
import { useState } from 'react'
import { api } from '../lib/api'
import { useAsync } from '../hooks/useAsync'
import { Button, Card, ErrorState, KV, Mono, Spinner } from './ui'

type P = Record<string, Record<string, unknown> & unknown>

function get(o: unknown, ...path: string[]): unknown {
  return path.reduce<unknown>((acc, k) => (acc && typeof acc === 'object' ? (acc as Record<string, unknown>)[k] : undefined), o)
}

export function PassportViewer({ sessionId }: { sessionId: string }) {
  const { data, error, loading, reload } = useAsync((s) => api.passport(sessionId, s), [sessionId])
  const [copied, setCopied] = useState(false)
  if (loading && !data) return <Spinner label="Building passport…" />
  if (error) return <ErrorState error={error} onRetry={reload} />
  const p = data as P
  const json = JSON.stringify(p, null, 2)
  const download = () => {
    const url = URL.createObjectURL(new Blob([json], { type: 'application/json' }))
    const a = Object.assign(document.createElement('a'), { href: url, download: `zerosetup-passport-${sessionId}.json` })
    a.click()
    URL.revokeObjectURL(url)
  }
  const manifests = (get(p, 'dependencies', 'manifests') as { file: string; sha256: string; lockfile: boolean }[]) ?? []
  const steps = (get(p, 'execution', 'steps') as { id: string; argv: string[]; exitCode?: number; skipped?: boolean }[]) ?? []
  return (
    <div className="grid lg:grid-cols-2 gap-4">
      <Card title="Reproducibility passport" actions={<>
        <Button size="sm" variant="ghost" onClick={() => { void navigator.clipboard.writeText(json); setCopied(true); setTimeout(() => setCopied(false), 1500) }}
          icon={copied ? <Check className="size-3.5" aria-hidden /> : <Copy className="size-3.5" aria-hidden />}>{copied ? 'Copied' : 'Copy'}</Button>
        <Button size="sm" onClick={download} icon={<Download className="size-3.5" aria-hidden />}>Export JSON</Button>
      </>}>
        <dl className="text-[13px]">
          <KV label="Schema">{String(get(p, 'schemaVersion'))} · generated by zerosetup {String(get(p, 'generator', 'version'))}</KV>
          <KV label="Source"><Mono>{String(get(p, 'source', 'repository') ?? get(p, 'source', 'kind'))}</Mono></KV>
          <KV label="Commit"><Mono>{String(get(p, 'source', 'commit') ?? '— (local, content-hashed)')}</Mono></KV>
          <KV label="Content hash"><Mono className="break-all">{String(get(p, 'source', 'contentHash'))}</Mono></KV>
          <KV label="Runtime">{String(get(p, 'environment', 'runtime'))} {String(get(p, 'environment', 'runtimeVersion'))} · {String(get(p, 'environment', 'framework'))}</KV>
          <KV label="Base image"><Mono className="break-all">{String(get(p, 'environment', 'baseImageDigest') ?? get(p, 'environment', 'baseImage'))}</Mono></KV>
          <KV label="Platform">{String(get(p, 'platform', 'engine') ?? '')} {String(get(p, 'platform', 'engineVersion') ?? '')} · {String(get(p, 'platform', 'engineOs') ?? '')} {String(get(p, 'platform', 'engineArch') ?? '')}</KV>
          <KV label="Plan hash"><Mono className="break-all">{String(get(p, 'execution', 'planHash'))}</Mono></KV>
          <KV label="Status">{String(get(p, 'execution', 'status'))}</KV>
        </dl>
      </Card>
      <div className="space-y-4">
        <Card title="Dependency inputs">
          {manifests.length === 0 ? <p className="text-muted text-[13px]">No manifests recorded.</p> : (
            <ul className="space-y-1 text-xs">
              {manifests.map((m) => <li key={m.file} className="flex gap-3"><Mono className="w-40 shrink-0">{m.file}</Mono><Mono className="text-muted truncate">{m.sha256}</Mono></li>)}
            </ul>
          )}
        </Card>
        <Card title="Executed steps">
          <ul className="space-y-1 text-xs">
            {steps.map((s) => <li key={s.id}><Mono>{s.argv.join(' ')}</Mono> <span className="text-muted">{s.skipped ? 'skipped (cache)' : s.exitCode !== undefined ? `exit ${s.exitCode}` : 'not run'}</span></li>)}
          </ul>
        </Card>
        <Card title="Excluded from this record">
          <ul className="text-xs text-muted space-y-1">{((get(p, 'exclusions') as string[]) ?? []).map((e) => <li key={e}>• {e}</li>)}</ul>
        </Card>
      </div>
    </div>
  )
}
